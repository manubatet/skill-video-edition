"""Apply cut decisions (retakes, removed words, silences), clean audio, re-time the transcript.

Usage:
  python build_edit.py --work work/ [--edit work/edit.json]

Reads  work/transcript.json and work/edit.json (all fields optional):
  {
    "remove_sentences": [3, 7],        # sentence ids (retakes, off-topic)
    "remove_words": [[120, 131]],      # inclusive ranges of word ids (false starts)
    "max_gap": 0.40,                   # pauses longer than this are cut (s)
    "pad": 0.12,                       # breathing room kept around speech (s)
    "denoise": "auto",                 # auto | off | light (FFmpeg afftdn) | deepfilter (DeepFilterNet CLI)
                                       # auto = light only if the pauses are noisy (clean audio stays untouched)
    "loudness": -14,                   # integrated LUFS target
    "voice_patches": [{"id": "p1", "words": [40, 42], "text": "..."}]  # see voice_clone.py
  }
Voice patches replace the audio of a word range (source time) with a clip generated by
voice_clone.py, fitted to the original span (sped up by at most PATCH_MAX_STRETCH, padded with
room tone if shorter), so no timestamp moves. The video frames stay; fix the words' captions
text in transcript.json as usual. When patches are present the cut audio is mono.
Writes work/segments.json, work/transcript_edited.json, work/transcript_edited.txt, work/cut.mkv
All word ids stay the ORIGINAL ids, so later steps can reference them safely.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from common import die, filter_script, load, need, run, save, wav_duration, write_readable  # noqa: E402

DEFAULTS = {"remove_sentences": [], "remove_words": [], "max_gap": 0.40, "pad": 0.12,
            "denoise": "auto", "loudness": -14, "voice_patches": []}
NOISY_DB = -50  # pause level above which "auto" denoises
PATCH_MAX_STRETCH = 1.20  # a generated clip may be sped up by this much to fit its span
SR = 48000


def plan_segments(t, cfg):
    words = t["words"]
    removed = set()
    for sid in cfg["remove_sentences"]:
        s = next((s for s in t["sentences"] if s["id"] == sid), None)
        if s is None:
            die(f"remove_sentences: sentence {sid} does not exist")
        removed.update(s["words"])
    for a, b in cfg["remove_words"]:
        removed.update(range(a, b + 1))
    kept = [w for w in words if w["i"] not in removed]
    if not kept:
        die("Every word was removed; nothing left to render.")

    groups, cur = [], [kept[0]]
    for prev, w in zip(kept, kept[1:]):
        contiguous = w["i"] == prev["i"] + 1
        if contiguous and (w["start"] - prev["end"]) <= cfg["max_gap"]:
            cur.append(w)
        else:
            groups.append(cur)
            cur = [w]
    groups.append(cur)

    fps, dur, pad = t["fps"], t["duration"], cfg["pad"]
    segs = []
    for g in groups:
        first, last = g[0], g[-1]
        start = first["start"] - pad
        if first["i"] > 0:
            before = words[first["i"] - 1]
            limit = before["end"] + 0.01 if before["i"] in removed else (before["end"] + first["start"]) / 2
            start = max(start, limit)
        end = last["end"] + pad
        if last["i"] + 1 < len(words):
            after = words[last["i"] + 1]
            limit = after["start"] - 0.01 if after["i"] in removed else (last["end"] + after["start"]) / 2
            end = min(end, limit)
        # snap to the frame grid so audio and video cut at identical instants (no drift)
        start = max(0.0, round(start * fps) / fps)
        end = min(dur, round(end * fps) / fps)
        if end - start >= 1.0 / fps:
            segs.append({"src_start": round(start, 4), "src_end": round(end, 4), "words": [w["i"] for w in g]})

    merged = [segs[0]]
    for s in segs[1:]:  # join segments that touch after snapping
        if s["src_start"] - merged[-1]["src_end"] < 0.5 / fps:
            merged[-1]["src_end"] = s["src_end"]
            merged[-1]["words"] += s["words"]
        else:
            merged.append(s)
    off = 0.0
    for s in merged:
        s["out_start"] = round(off, 4)
        off += s["src_end"] - s["src_start"]
        s["out_end"] = round(off, 4)
    return merged, removed


def retime(t, segs):
    words_by_id = {w["i"]: w for w in t["words"]}
    new_words = []
    for s in segs:
        for i in s["words"]:
            w = dict(words_by_id[i])
            w["start"] = round(s["out_start"] + w["start"] - s["src_start"], 3)
            w["end"] = round(min(s["out_start"] + w["end"] - s["src_start"], s["out_end"]), 3)
            new_words.append(w)
    kept_ids = {w["i"] for w in new_words}
    idx = {w["i"]: k for k, w in enumerate(new_words)}
    sentences = []
    for s in t["sentences"]:
        ids = [i for i in s["words"] if i in kept_ids]
        if not ids:
            continue
        ws = [new_words[idx[i]] for i in ids]
        sentences.append({**s, "words": ids, "text": " ".join(w["text"] for w in ws),
                          "start": ws[0]["start"], "end": ws[-1]["end"]})
    duration = segs[-1]["out_end"]
    return {**t, "duration": round(duration, 3), "edited": True, "sentences": sentences, "words": new_words}


def pause_level_db(src, t, work):
    """Median level (dBFS) of 50 ms frames in the gaps between words: the background noise.
    The median ignores breaths, which would dominate an average."""
    from voice_clone import read_wav
    wav = work / "pauses_probe.wav"
    run(["ffmpeg", "-y", "-i", str(src), "-vn", "-ac", "1", "-ar", "16000", str(wav)])
    x, sr = read_wav(wav)
    wav.unlink()
    ws = t["words"]
    n, levels = int(0.05 * sr), []
    for a, b in zip(ws, ws[1:]):
        if b["start"] - a["end"] > 0.3:
            g = x[int((a["end"] + 0.08) * sr):int((b["start"] - 0.08) * sr)]
            fr = g[: len(g) // n * n].reshape(-1, n)
            levels += list(20 * np.log10(np.sqrt((fr ** 2).mean(axis=1)) + 1e-9))
    return float(np.median(levels)) if levels else None


def denoise_source(src, mode, work, t=None):
    """Return (path, extra_filter) for the audio to cut from."""
    if mode == "auto":
        level = pause_level_db(src, t, work) if t else None
        mode = "light" if level is not None and level > NOISY_DB else "off"
        print(f"denoise auto: pauses at {'n/a' if level is None else f'{level:.0f} dBFS'} -> {mode}")
    if mode == "off":
        return src, ""
    if mode == "deepfilter":
        if not shutil.which("deepFilter"):
            print("WARNING: deepFilter CLI not found (pip install deepfilternet); falling back to 'light'")
            return src, "afftdn=nf=-25,"
        wav = work / "src_audio.wav"
        run(["ffmpeg", "-y", "-i", str(src), "-vn", "-ac", "1", "-ar", "48000", str(wav)])
        run(["deepFilter", str(wav), "-o", str(work / "df")])
        out = next((work / "df").glob("*.wav"), None)
        if out is None:
            die("DeepFilterNet produced no output")
        return out, ""
    return src, "afftdn=nf=-25,"  # light: gentle broadband noise reduction


def room_tone(x, sr, length):
    """Loop the quietest 0.5 s of the recording to fill gaps so they don't sound like dropouts."""
    n, k = int(sr * 0.02), 25
    rms = np.sqrt((x[: len(x) // n * n].reshape(-1, n) ** 2).mean(axis=1))
    if len(rms) <= k:
        return np.zeros(length, dtype=np.float32)
    win = np.convolve(rms, np.ones(k), "valid")
    tone = x[int(win.argmin()) * n: (int(win.argmin()) + k) * n]
    return np.tile(tone, length // len(tone) + 1)[:length]


def patch_audio(audio_src, t, cfg, removed, work):
    """Splice voice_clone.py clips over their word spans; return the patched mono wav."""
    from voice_clone import read_wav, write_wav
    words = {w["i"]: w for w in t["words"]}
    man_path = work / "voice" / "manifest.json"
    manifest = load(man_path) if man_path.exists() else {}
    full = work / "src_audio_mono.wav"
    run(["ffmpeg", "-y", "-i", str(audio_src), "-vn", "-ac", "1", "-ar", str(SR), str(full)])
    x, _ = read_wav(full)
    spans = []
    for p in cfg["voice_patches"]:
        a_id, b_id = p["words"]
        if a_id not in words or b_id not in words or b_id < a_id:
            die(f"voice patch {p['id']}: bad word range {p['words']}")
        if any(i in removed for i in range(a_id, b_id + 1)):
            die(f"voice patch {p['id']}: words {p['words']} overlap removed words")
        clip = work / "voice" / f"{p['id']}.wav"
        if not clip.exists() or manifest.get(p["id"], {}).get("text") != p.get("text", "").strip():
            die(f"voice patch {p['id']}: clip missing or out of date; run voice_clone.py first")
        a, b = words[a_id]["start"], words[b_id]["end"]
        if any(a < e and s < b for s, e in spans):
            die(f"voice patch {p['id']} overlaps another patch")
        spans.append((a, b))
        d, g = b - a, wav_duration(clip)
        if g > d * PATCH_MAX_STRETCH:
            die(f"voice patch {p['id']}: clip is {g:.2f}s but the span is {d:.2f}s (max x{PATCH_MAX_STRETCH}). "
                f"Shorten the text or widen the word range.")
        af = f"atempo={g / d:.4f}," if g > d else ""
        fitted = work / "voice" / f"{p['id']}_fit.wav"
        run(["ffmpeg", "-y", "-i", str(clip), "-af", f"{af}aresample={SR}", "-ac", "1", str(fitted)])
        y, _ = read_wav(fitted)
        s0, s1 = int(a * SR), min(len(x), int(b * SR))
        L = s1 - s0
        seg = room_tone(x, SR, L) + np.pad(y[:L], (0, max(0, L - len(y))))
        f = min(int(0.015 * SR), L // 4)
        ramp = np.linspace(0, 1, f, dtype=np.float32)
        seg[:f] *= ramp
        seg[L - f:] *= ramp[::-1]
        x[s0:s0 + f] *= ramp[::-1]
        x[s1 - f:s1] *= ramp
        x[s0 + f:s1 - f] = 0
        x[s0:s1] += seg
        print(f"voice patch {p['id']}: w{a_id}-w{b_id} {a:.2f}-{b:.2f}s, clip {g:.2f}s"
              + (f" (x{g / d:.2f})" if g > d else f" (+{d - g:.2f}s room tone)"))
    out = work / "src_audio_patched.wav"
    write_wav(out, x, SR)
    full.unlink(missing_ok=True)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", default="work")
    ap.add_argument("--edit", default=None)
    args = ap.parse_args()
    need("ffmpeg")
    work = Path(args.work)
    t = load(work / "transcript.json")
    if not t.get("has_audio", True):
        die("the source video has no audio track")
    edit_path = Path(args.edit) if args.edit else work / "edit.json"
    cfg = {**DEFAULTS, **(load(edit_path) if edit_path.exists() else {})}

    segs, removed = plan_segments(t, cfg)
    save({"segments": segs, "config": cfg}, work / "segments.json")
    edited = retime(t, segs)
    save(edited, work / "transcript_edited.json")
    write_readable(edited, work / "transcript_edited.txt")

    audio_src, afilter = denoise_source(Path(t["source"]), cfg["denoise"], work, t)
    if cfg["voice_patches"]:
        audio_src = patch_audio(audio_src, t, cfg, removed, work)
    fc, labels = [], []
    for k, s in enumerate(segs):
        a, b = s["src_start"], s["src_end"]
        d = b - a
        fade = min(0.012, d / 4)
        fc.append(f"[0:v]trim=start={a}:end={b},setpts=PTS-STARTPTS[v{k}]")
        fc.append(f"[1:a]atrim=start={a}:end={b},asetpts=PTS-STARTPTS,"
                  f"afade=t=in:d={fade:.3f},afade=t=out:st={d - fade:.3f}:d={fade:.3f}[a{k}]")
        labels.append(f"[v{k}][a{k}]")
    fc.append(f"{''.join(labels)}concat=n={len(segs)}:v=1:a=1[vc][ac0]")
    fc.append(f"[ac0]{afilter}aresample=48000[ac]")
    raw = work / "cut_raw.mkv"
    graph = work / "cut_graph.txt"
    graph.write_text(";\n".join(fc), encoding="utf-8")
    run(["ffmpeg", "-y", "-i", t["source"], "-i", str(audio_src), *filter_script(graph),
         "-map", "[vc]", "-map", "[ac]", "-c:v", "libx264", "-crf", "14", "-preset", "fast",
         "-pix_fmt", "yuv420p", "-fps_mode", "cfr", "-r", str(t["fps"]), "-c:a", "pcm_s16le", str(raw)])

    # Two-pass loudness normalization (EBU R128) to the platform target.
    lufs = cfg["loudness"]
    p = run(["ffmpeg", "-i", str(raw), "-vn", "-af", f"loudnorm=I={lufs}:TP=-1.5:LRA=11:print_format=json",
             "-f", "null", "-"])
    m = json.loads(p.stderr[p.stderr.rindex("{"):p.stderr.rindex("}") + 1])
    ln = (f"loudnorm=I={lufs}:TP=-1.5:LRA=11:measured_I={m['input_i']}:measured_TP={m['input_tp']}:"
          f"measured_LRA={m['input_lra']}:measured_thresh={m['input_thresh']}:offset={m['target_offset']}:linear=true")
    run(["ffmpeg", "-y", "-i", str(raw), "-c:v", "copy", "-af", f"{ln},aresample=48000",
         "-c:a", "pcm_s16le", str(work / "cut.mkv")])
    raw.unlink(missing_ok=True)

    saved = t["duration"] - edited["duration"]
    print(f"OK: {len(segs)} segments, removed {len(removed)} words, "
          f"{t['duration']:.1f}s -> {edited['duration']:.1f}s (-{saved:.1f}s). "
          f"Input loudness {m['input_i']} LUFS -> {lufs}. Wrote {work/'cut.mkv'}")


if __name__ == "__main__":
    main()
